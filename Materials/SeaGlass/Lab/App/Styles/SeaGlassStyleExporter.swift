import Foundation

struct SeaGlassStyleExportFiles: Sendable {
    let jsonURL: URL
    let swiftURL: URL
}

enum SeaGlassStyleExporter {
    static func jsonData(styles: [SeaGlassStyle], exportedAt: Date = Date()) throws -> Data {
        let formatter = ISO8601DateFormatter()
        let envelope = ExportEnvelope(
            version: 1,
            metadata: Metadata(
                name: "Metro Sea Glass styles", exportedAt: formatter.string(from: exportedAt),
                materialRecipeRevision: 2,
                minimumIOS: "26.0", colorSpace: "sRGB; RGB doubles are canonical",
                artisticMeanings: [
                    "frost": "Dimensionless milky veil, not native blur radius or measured scattering.",
                    "depth": "Dimensionless illustrated bevel and contact shadow, not physical thickness.",
                    "grain": "Dimensionless static micrograin intensity.",
                    "lightAngleDegrees": "Degrees clockwise from right in screen coordinates; perimeter only.",
                    "cornerRadius": "Layout points; permitted lab range 12...64.",
                    "appearance": "Metro dark canvas or Mineral light canvas; the host owns surroundings.",
                    "forceOpaque": "Additive preview flag ORed with system Reduce Transparency.",
                    "staticLight": "Additive preview flag ORed with system Reduce Motion."
                ]
            ),
            tintCanonicalRGB: Dictionary(uniqueKeysWithValues: SeaGlassStyleTint.allCases.map { ($0.rawValue, $0.canonicalRGB) }),
            styles: styles,
            swiftSource: swiftSource(styles: styles)
        )
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
        return try encoder.encode(envelope)
    }

    /// Names and notes are escaped string data; generated identifiers never derive from user input.
    static func swiftSource(styles: [SeaGlassStyle]) -> String {
        let definitions = styles.enumerated().map { index, style in
            """
                public static let style\(index + 1) = Recipe(
                    id: \(literal(style.id.uuidString)),
                    name: \(literal(style.name)),
                    notes: \(literal(style.notes)),
                    tint: .\(style.tint.rawValue), appearance: .\(style.appearance.rawValue),
                    frost: \(number(style.frost)), depth: \(number(style.depth)), grain: \(number(style.grain)),
                    lightAngleDegrees: \(number(style.lightAngleDegrees)), cornerRadius: \(number(style.cornerRadius)),
                    forceOpaque: \(style.forceOpaque), staticLight: \(style.staticLight)
                )
            """
        }.joined(separator: "\n\n")
        let all = styles.indices.map { "style\($0 + 1)" }.joined(separator: ", ")
        return """
        // Generated by Sea Glass Lab. Artistic material recipes; no physical optics claim.
        // Material recipe revision 2: isolated native backdrop and soft inward pigment shoulder.
        // Frost is an overlay. Light direction affects only the rim. Respect system accessibility.
        import Foundation
        import SwiftUI
        import MetroSeaGlass

        @MainActor
        public enum SeaGlassSavedStyles {
            public enum Appearance: String { case metro, mineral }

            public struct Recipe {
                public let id: String
                public let name: String
                public let notes: String
                public let tint: SeaGlassTint
                public let appearance: Appearance
                public let lightAngleDegrees: Double
                public let cornerRadius: CGFloat
                public let configuration: SeaGlassConfiguration

                public init(id: String, name: String, notes: String, tint: SeaGlassTint,
                            appearance: Appearance, frost: Double, depth: Double, grain: Double,
                            lightAngleDegrees: Double, cornerRadius: Double,
                            forceOpaque: Bool, staticLight: Bool) {
                    self.id = id
                    self.name = name
                    self.notes = notes
                    self.tint = tint
                    self.appearance = appearance
                    self.lightAngleDegrees = lightAngleDegrees
                    self.cornerRadius = CGFloat(cornerRadius)
                    let radians = lightAngleDegrees * .pi / 180
                    self.configuration = SeaGlassConfiguration(
                        frost: frost, depth: depth,
                        lightDirection: SeaGlassLightDirection(x: cos(radians), y: sin(radians)),
                        grain: grain, forceOpaque: forceOpaque, staticLight: staticLight
                    )
                }
            }

        \(definitions)

            public static let all: [Recipe] = [\(all)]
        }

        """
    }

    static func exportFiles(styles: [SeaGlassStyle], directory: URL? = nil) throws -> SeaGlassStyleExportFiles {
        let destination = directory ?? FileManager.default.temporaryDirectory
            .appendingPathComponent("SeaGlassStyles-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: destination, withIntermediateDirectories: true)
        let jsonURL = destination.appendingPathComponent("SeaGlassStyles.json")
        let swiftURL = destination.appendingPathComponent("SeaGlassSavedStyles.swift")
        try jsonData(styles: styles).write(to: jsonURL, options: .atomic)
        try Data(swiftSource(styles: styles).utf8).write(to: swiftURL, options: .atomic)
        return SeaGlassStyleExportFiles(jsonURL: jsonURL, swiftURL: swiftURL)
    }

    private static func number(_ value: Double) -> String { String(value) }

    private static func literal(_ value: String) -> String {
        let escaped = value.unicodeScalars.map { scalar -> String in
            switch scalar.value {
            case 0x22: "\\\""
            case 0x5C: "\\\\"
            case 0x0A: "\\n"
            case 0x0D: "\\r"
            case 0x09: "\\t"
            case 0x00...0x1F, 0x7F, 0x2028, 0x2029: "\\u{\(String(scalar.value, radix: 16))}"
            default: String(scalar)
            }
        }.joined()
        return "\"\(escaped)\""
    }

    private struct ExportEnvelope: Encodable {
        let version: Int
        let metadata: Metadata
        let tintCanonicalRGB: [String: [Double]]
        let styles: [SeaGlassStyle]
        let swiftSource: String
    }

    private struct Metadata: Encodable {
        let name: String
        let exportedAt: String
        let materialRecipeRevision: Int
        let minimumIOS: String
        let colorSpace: String
        let artisticMeanings: [String: String]
    }
}
